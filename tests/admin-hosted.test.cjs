const { test } = require('node:test');
const assert = require('node:assert/strict');
test('hosted API enforces exact CORS origin and sessions for every gateway command', async t => {
  const { createApp } = await import('../server.mjs');
  const { hashPassword } = await import('../admin-auth.mjs');
  const calls = [];
  const origin = 'https://savant777.github.io';
  const app = createApp({ production: true, appOrigin: origin, passwordHash: await hashPassword('test-only-hosted-password'), gateway: { configured: true, call: async (command, request, session) => { calls.push({ command, request, session }); return command === 'bootstrap' ? { players: [], userIds: [] } : { ok: true }; } } });
  await new Promise(resolve => app.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => app.close(resolve)));
  const base = `http://127.0.0.1:${app.address().port}`;
  const post = (route, input = {}, token = '', source = origin) => fetch(`${base}/api/admin/${route}`, { method: 'POST', headers: { Origin: source, 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: JSON.stringify(input) });
  const preflight = await fetch(`${base}/api/admin/login`, { method: 'OPTIONS', headers: { Origin: origin, 'Access-Control-Request-Headers': 'content-type, authorization' } });
  assert.equal(preflight.status, 204);
  assert.equal(preflight.headers.get('access-control-allow-origin'), origin);
  assert.equal(preflight.headers.get('access-control-allow-credentials'), null);
  assert.equal((await post('login', {}, '', 'https://evil.example')).status, 403);
  for (const route of ['bootstrap', 'preview', 'commit']) assert.equal((await post(route)).status, 401);
  assert.equal(calls.length, 0);
  const login = await post('login', { operator: 'Admin', password: 'test-only-hosted-password' });
  assert.equal(login.status, 200);
  assert.equal(login.headers.get('set-cookie'), null);
  const { token } = await login.json();
  assert.match(token, /^[a-f0-9]{64}$/);
  assert.equal((await post('bootstrap', {}, token)).status, 200);
  assert.equal((await post('preview', { action: 'inactive' }, token)).status, 400);
  assert.equal((await post('preview', { action: 'register', operator: 'forged-person', values: {} }, token)).status, 200);
  assert.equal((await post('preview', { action: 'edit', values: {} }, token)).status, 200);
  assert.equal((await post('preview', { action: 'npc', values: {} }, token)).status, 200);
  assert.equal((await post('preview', { action: 'race', values: {} }, token)).status, 200);
  assert.equal((await post('commit', { requestId: 'example', owner: 'fabricated' }, token)).status, 200);
  assert.deepEqual(calls.map(call => call.command), ['bootstrap', 'preview', 'preview', 'preview', 'preview', 'commit']);
  assert.ok(calls.every(call => call.session.operator === 'Admin' && /^[a-f0-9]{64}$/.test(call.session.owner)));
  await post('logout', {}, token);
  assert.equal((await post('commit', {}, token)).status, 401);
  assert.equal((await fetch(`${base}/admin-sample-data.js`)).status, 404);
  assert.equal((await fetch(`${base}/admin-config.js`)).status, 404);
  assert.equal((await fetch(`${base}/health`)).status, 200);
});
